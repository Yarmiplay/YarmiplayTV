/**
 * SHA-256 and MD5 of text, synchronously. WebCrypto's digest is asynchronous (and has no MD5), but filename matching
 * compares hashed names inside synchronous checks, and the Hello sends the server password as an MD5, as Syncplay does.
 */

const utf8 = new TextEncoder();

const toHex = (bytes: Uint8Array) => Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");

